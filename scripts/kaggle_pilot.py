"""Kaggle launcher for the specifically authorized 60-pair / 3-epoch pilot."""

from importlib import metadata
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys


REPO = Path(__file__).resolve().parents[1]
EXPECTED_SHA = '8d18337f766102f951ac0ca543a22536f58caeb6b6c33cfef73326f866791286'
CONFIG_BLOB = 'c9fdc6e00efb549e4db21c32d97cb2f8fbb29366'


def main():
    working = Path('/kaggle/working')
    if not working.is_dir():
        raise RuntimeError('Run only inside Kaggle; never fetch SAT weights locally')
    output = working/'PV-DINOV3/outputs/pilot'
    output.mkdir(parents=True, exist_ok=True)
    if (output/'history.json').exists() or (output/'completion.json').exists():
        raise RuntimeError('Pilot already has results; refusing automatic retraining')
    os.chdir(REPO)
    sys.path.insert(0, str(REPO))
    inventory, candidates = [], []
    for mount in ['/kaggle/input', '/kaggle/working']:
        for parent, dirs, files in os.walk(mount):
            dirs.sort()
            inventory.append({'path': parent, 'files_here': len(files)})
            for name in files:
                if name.endswith('.safetensors') or name == EXPECTED_SHA:
                    path = Path(parent)/name
                    candidates.append({'path': str(path), 'size_bytes': path.stat().st_size})
    (output/'mount_cache_inspection.json').write_text(json.dumps({'directories': inventory,
        'cache_candidates': candidates, 'raw_pixels_read_by_inspection': 0}, indent=2), encoding='utf-8')
    # Preserve the provided CUDA torch builds and the previously verified API.
    if metadata.version('timm') != '1.0.29':
        subprocess.run([sys.executable, '-m', 'pip', 'install', '--no-deps', 'timm==1.0.29'], check=True)
    if metadata.version('torch') != '2.11.0+cu128':
        raise RuntimeError('torch differs from verified Smoke environment; stop for compatibility review')
    with (output/'core_tests.txt').open('w') as stream:
        tested = subprocess.run([sys.executable, '-m', 'unittest', 'discover', '-s', 'tests', '-v'],
                                stdout=stream, stderr=subprocess.STDOUT)
    print((output/'core_tests.txt').read_text(), flush=True)
    tested.check_returncode()
    from pvseg.data import CATEGORIES, discover_root, read_manifest
    from pvseg.spatial import spatial_pilot_split
    from pvseg.model import sha256_file
    from pvseg.runtime import write_json

    root = discover_root('/kaggle/input')
    rows = read_manifest(root)
    _, _, groups = spatial_pilot_split(rows, CATEGORIES, 42)
    evidence = []
    for path in sorted((root/'processing_code').rglob('*.py')):
        lines = path.read_text(encoding='utf-8-sig').splitlines()
        for index, line in enumerate(lines):
            if 'source_label_uncertain_filename' in line:
                evidence.append({'file': str(path.relative_to(root)), 'line': index+1, 'source': line.strip()})
    write_json(output/'label_source_report.json', {'evidence': evidence,
        'meaning': 'Flag generated by checking the source SHP filename for the Chinese uncertain marker; not a pixel ignore label or verified label error.',
        'policy': 'Masks unchanged; no silent removal/relabeling; original annotation acceptance criteria remain unknown.',
        'manifest_rows': len(rows), 'flagged_rows': sum(r['source_label_uncertain_filename'].lower() == 'true' for r in rows)})
    write_json(output/'pretraining_groups.json', groups)
    restored = None
    recovery = {'cache_candidates': candidates, 'action': 'fixed official revision download inside Kaggle if no matching cache'}
    for candidate in candidates:
        path = Path(candidate['path'])
        config = path.with_name('config.json')
        if not config.is_file() and path.name == EXPECTED_SHA:
            config = path.with_name(CONFIG_BLOB)
        if config.is_file() and sha256_file(path) == EXPECTED_SHA:
            cfg = json.loads(config.read_text())
            if cfg.get('architecture') != 'vit_large_patch16_dinov3' or cfg.get('pretrained_cfg', {}).get('tag') != 'sat493m':
                continue
            restored = working/'verified_sat/model.safetensors'
            restored.parent.mkdir(exist_ok=True)
            if path.resolve() != restored.resolve():
                shutil.copy2(path, restored)
            shutil.copy2(config, restored.with_name('config.json'))
            recovery.update(action='restored verified cached bytes within Kaggle', source=str(path), sha256=EXPECTED_SHA)
            break
    write_json(output/'weight_recovery.json', recovery)
    command = [sys.executable, str(REPO/'train_pv896.py'), '--allow_pilot', '--data_root', str(root),
               '--epochs', '3', '--batch_size', '1', '--seed', '42', '--output_dir', str(output)]
    command.extend(['--weights', str(restored)] if restored else ['--download_weights'])
    print('AUTHORIZED: <=60 unique pairs, <=20/category, 3 epochs, batch=1, fixed model/loss.', flush=True)
    subprocess.run(command, check=True)
    # Kaggle output export can omit HF snapshot symlinks: retain real files too.
    completion = json.loads((output/'completion.json').read_text())
    source = completion['weight_source']
    stable = working/'verified_sat'
    stable.mkdir(exist_ok=True)
    for src, name in [(source['path'], 'model.safetensors'), (source['config_path'], 'config.json')]:
        if Path(src).resolve() != (stable/name).resolve():
            shutil.copy2(src, stable/name)
    write_json(output/'persisted_weight_files.json', {'weight_path': str(stable/'model.safetensors'),
        'weight_sha256': sha256_file(stable/'model.safetensors'), 'config_path': str(stable/'config.json'),
        'downloaded_to_local': False, 'github_contains_weights': False})
    print('STOP: no further training. Results await user confirmation.', flush=True)


if __name__ == '__main__':
    main()
